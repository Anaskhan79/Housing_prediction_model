import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

df = pd.read_csv("USA_Housing.csv")

df.head()

df.info()

df.describe()

df.shape

"""### Exploring DATA_set"""

sns.pairplot(df)

"""* Avg. Area Income → Price (Strong Positive Correlation)
As income increases, house prices rise significantly. This is the strongest predictor in your dataset.
* Avg. Area Number of Rooms → Price (Moderate Positive)
More rooms generally mean higher prices, but the relationship is slightly scattered.
* Area Population → Price (Moderate Positive)
Densely populated areas tend to have higher property prices.
* Avg. Area House Age → Price (Weak Positive)
Older areas slightly correlate with higher prices, but the effect is not strong.
*  Avg. Area Number of Bedrooms → Price (Very Weak / Noisy)
Bedrooms are discrete and show little clear impact, suggesting redundancy with "Rooms".




"""

plt.figure(figsize=(10,6))
sns.heatmap(df.corr(numeric_only=True), annot=True, cmap='coolwarm')
plt.title("Correlation Heatmap")
plt.show()

sns.scatterplot(x='Avg. Area Income', y='Price', data=df)
plt.show()

sns.scatterplot(x='Avg. Area Number of Rooms', y='Price', data=df)
plt.show()

sns.scatterplot(x='Area Population', y='Price', data=df)
plt.show()

"""* Positive correlation exists → As the average number of rooms increases, house prices generally increase.
This confirms that larger homes tend to be more expensive, which aligns with real-world expectations.
* Strength of Relationship
The trend is moderate, not very strong.
Points are widely scattered → meaning rooms alone cannot predict price accurately.
Other features (like income) are also influencing price.
* Data Spread & Variability
For the same number of rooms (e.g., ~7), prices vary a lot (₹5L to ₹20L+)
This indicates high variance, suggesting:
Location/income factors matter
Rooms ≠ luxury or quality
"""

df['Income_per_Person'] = df['Avg. Area Income'] / df['Area Population']
df['Rooms_per_House'] = df['Avg. Area Number of Rooms'] / df['Avg. Area House Age']

plt.figure(figsize=(8,5))
sns.histplot(df['Price'], bins=30, kde=True)
plt.title("Distribution of House Prices")
plt.xlabel("Price")
plt.ylabel("Frequency")
plt.show()

"""*  The target variable (Price) follows an approximately normal (bell-shaped) distribution, which is ideal for linear regression models.
* The distribution shows low skewness, indicating that house prices are fairly balanced without heavy distortion toward extremely high or low values.
* There are no significant outliers, suggesting the dataset is clean and unlikely to negatively impact model performance

### Linear regression model
"""

X = df[['Avg. Area Income', 'Avg. Area House Age', 'Avg. Area Number of Rooms'
               , 'Area Population']]

y = df['Price']

"""* Splitting the data into  x_train and y_train."""

from sklearn.model_selection import train_test_split

X_train, X_test, y_train, y_test = train_test_split(X, y, test_size=0.4, random_state=101)

"""### Creating model

"""

from sklearn.linear_model import LinearRegression

lm = LinearRegression()

lm.fit(X_train,y_train)

"""### LinearRegression Model Evaluation"""

print(lm.intercept_)

"""* Your features have large values (e.g., income in tens of thousands)
* The model adjusts by shifting the baseline downward
* This ensures the regression line fits the data properly

* It’s a mathematical adjustment, not a real price
"""

coeff_df = pd.DataFrame(lm.coef_,X.columns,columns=['Coefficient'])
coeff_df

"""* Price=b0+b1(Income)+b2(House Age)+b3(Rooms)+b4(Population)

* Each coefficient tells you:

* “If this feature increases by 1 unit, how much will Price change (keeping others constant)”
"""

predictions = lm.predict(X_test)

plt.scatter(y_test,predictions)

"""* Points are closely clustered along a straight diagonal line.
* Your model is highly accurate

"""

sns.distplot((y_test-predictions),bins=50);

from sklearn import metrics

print('MAE:', metrics.mean_absolute_error(y_test, predictions))
print('MSE:', metrics.mean_squared_error(y_test, predictions))
print('RMSE:', np.sqrt(metrics.mean_squared_error(y_test, predictions)))

"""* Predictions are consistently close to actual values
* Error is low relative to price range
* Model is reliable and stable
"""

